/// Upper bound on tracked subscriptions per session. Far above any legitimate
/// use (the suite exercises a handful) and low enough that an adversarial
/// client subscribing to endless distinct URIs cannot grow this server's
/// bookkeeping without bound.
const MAX_SUBSCRIPTIONS: usize = 1024;

/// Reference MCP server exercising the MCP protocol surface.
///
/// Construct with [`EverythingServer::new`] for `2025-11-25` or
/// [`EverythingServer::serving`] to choose a [`ServedRevision`], then serve
/// over any rmcp transport — stdio for subprocess wiring, streamable HTTP
/// behind the default-secure [`crate::policy::HttpSecurityPolicy`].
#[derive(Debug)]
pub struct EverythingServer {
    pub(crate) tool_router: ToolRouter<Self>,
    pub(crate) prompt_router: PromptRouter<Self>,
    /// URIs the client subscribed to (`resources/subscribe` bookkeeping).
    subscriptions: Arc<Mutex<HashSet<String>>>,
    /// Threshold set via `logging/setLevel`; messages below it are dropped.
    // SEP-2577 deprecates Logging; `2025-11-25` still requires it.
    #[allow(deprecated)]
    log_level: Arc<Mutex<LoggingLevel>>,
    /// The protocol revision this instance presents.
    revision: ServedRevision,
}

impl EverythingServer {
    /// Creates the server with every implemented capability wired, serving the
    /// default revision ([`ServedRevision::V2025_11_25`]).
    #[must_use]
    pub fn new() -> Self {
        Self::serving(ServedRevision::default())
    }

    /// Creates the server presenting `revision`.
    #[must_use]
    pub fn serving(revision: ServedRevision) -> Self {
        Self {
            tool_router: crate::tools::all_tools(revision),
            prompt_router: Self::prompt_router_all(),
            subscriptions: Arc::new(Mutex::new(HashSet::new())),
            log_level: Arc::new(Mutex::new(logging::default_level())),
            revision,
        }
    }

    /// The protocol revision this instance presents.
    #[must_use]
    pub const fn revision(&self) -> ServedRevision {
        self.revision
    }

    /// `result`, with SEP-2549 caching hints when the served revision defines
    /// them.
    fn cached<T: caching::Cacheable>(&self, result: T) -> T {
        caching::applied(self.revision, result)
    }

    /// `result`, naming this server in its `_meta` when the served revision
    /// asks that of every result (BASE-037).
    fn identified<T: identity::Identified>(&self, result: T) -> T {
        identity::applied(self.revision, &self.get_info().server_info, result)
    }

    /// Whether a message at `candidate` level may be emitted while answering
    /// `context`.
    ///
    /// Two mechanisms, one per revision, and the difference is a `MUST NOT`
    /// rather than a preference. `2025-11-25` carries a session threshold set
    /// by `logging/setLevel`, so anything at or above it is permitted for the
    /// whole session. `2026-07-28` removed that method: a client asks by
    /// putting `io.modelcontextprotocol/logLevel` in a *request's* `_meta`,
    /// and LOG-008 forbids emitting `notifications/message` for a request that
    /// did not (`server/utilities/logging#per-request-log-level`). So at the
    /// newer revision silence is the default and the request is the only thing
    /// that can lift it — a session threshold would be a threshold nobody set.
    // SEP-2577 deprecates Logging; `2025-11-25` still requires it.
    #[allow(deprecated)]
    pub(crate) fn log_permits(
        &self,
        context: &RequestContext<RoleServer>,
        candidate: LoggingLevel,
    ) -> bool {
        self.log_permitted_for(context.meta.log_level(), candidate)
    }

    /// [`Self::log_permits`], with the request's asked-for level already read.
    ///
    /// Split so the rule is testable: building a `RequestContext` needs a live
    /// peer, and the peer has no bearing on the decision.
    // SEP-2577 deprecates Logging; `2025-11-25` still requires it.
    #[allow(deprecated)]
    fn log_permitted_for(&self, asked: Option<LoggingLevel>, candidate: LoggingLevel) -> bool {
        if self.revision.is_stateless() {
            return asked.is_some_and(|asked| logging::permits(asked, candidate));
        }
        let threshold = self.log_level.lock().map_or_else(
            // A poisoned lock means a panicked writer; failing open keeps
            // diagnostics flowing exactly when something is going wrong.
            |poisoned| *poisoned.into_inner(),
            |level| *level,
        );
        logging::permits(threshold, candidate)
    }

    /// Snapshot of the subscribed URIs (test and tap support).
    #[must_use]
    pub fn subscribed_uris(&self) -> Vec<String> {
        let mut uris: Vec<String> = self.subscriptions.lock().map_or_else(
            |poisoned| poisoned.into_inner().iter().cloned().collect(),
            |subscriptions| subscriptions.iter().cloned().collect(),
        );
        uris.sort();
        uris
    }

    /// Records a subscription; returns whether the URI was newly tracked.
    ///
    /// The set is capped at [`MAX_SUBSCRIPTIONS`]: a client cannot grow this
    /// server's per-session bookkeeping without bound by subscribing to an
    /// endless stream of distinct URIs. At the cap, a new URI is refused (not
    /// tracked, no acknowledgement) while already-tracked URIs still re-confirm.
    pub(crate) fn track_subscription(&self, uri: String) -> bool {
        self.subscriptions.lock().is_ok_and(|mut subscriptions| {
            if subscriptions.contains(&uri) {
                return false;
            }
            if subscriptions.len() >= MAX_SUBSCRIPTIONS {
                return false;
            }
            subscriptions.insert(uri)
        })
    }

    /// Drops a subscription; returns whether the URI had been tracked.
    pub(crate) fn untrack_subscription(&self, uri: &str) -> bool {
        self.subscriptions
            .lock()
            .is_ok_and(|mut subscriptions| subscriptions.remove(uri))
    }
}

impl Default for EverythingServer {
    fn default() -> Self {
        Self::new()
    }
}

#[tool_handler(router = self.tool_router)]
impl ServerHandler for EverythingServer {
    // SEP-2577 deprecates Logging; `2025-11-25` still requires it.
    #[allow(deprecated)]
    fn get_info(&self) -> ServerConfig {
        // Not `Implementation::from_build_env()`: that helper expands
        // `env!(..)` inside rmcp and therefore always says "rmcp 1.x".
        ServerConfig::new(
            ServerCapabilities::builder()
                .enable_tools()
                .enable_tool_list_changed()
                .enable_resources()
                .enable_resources_subscribe()
                .enable_resources_list_changed()
                .enable_prompts()
                .enable_prompts_list_changed()
                .enable_logging()
                .enable_completions()
                .build(),
        )
        .with_server_info(
            Implementation::new(env!("CARGO_PKG_NAME"), env!("CARGO_PKG_VERSION"))
                .with_icons(fixtures::icons()),
        )
        .with_protocol_version(self.revision.protocol_version())
        .with_instructions(self.revision.instructions().to_owned())
    }

    async fn initialize(
        &self,
        request: InitializeRequestParams,
        context: RequestContext<RoleServer>,
    ) -> Result<InitializeResult, McpError> {
        let supported = self.supported_protocol_versions();
        if self.revision.is_stateless() {
            // A server serving only the stateless revision has no handshake to
            // complete, and rmcp's default would complete one anyway: its
            // negotiation answers an unsupported request with the server's own
            // version rather than an error. A legacy client would then read a
            // successful `initialize`, believe itself connected, and have every
            // subsequent request rejected for want of per-request metadata it
            // does not know to send.
            //
            // The refusal is `-32022` carrying `data.supported`, which is both
            // what VERS-001 requires of a version refusal and the diagnostic
            // VERS-008 asks a modern-only server to give a legacy client — the
            // one message such a client can surface, since it has no
            // fall-forward mechanism of its own.
            return Err(McpError::unsupported_protocol_version(
                request.protocol_version,
                &supported,
            ));
        }
        // rmcp's default body for the legacy surface, restated because
        // overriding a trait method forgoes it and its negotiation helper is
        // crate-private. Kept behaviourally identical on purpose: agree to the
        // requested version when it is one this server supports, and otherwise
        // answer with the server's own — the `2025-11-25` lifecycle rule,
        // which leaves the decision to disconnect with the client.
        context.peer.set_peer_info(request.clone());
        let mut info = self.get_info();
        if supported.contains(&request.protocol_version) {
            info.protocol_version = request.protocol_version;
        }
        Ok(info)
    }

    fn supported_protocol_versions(&self) -> Cow<'static, [ProtocolVersion]> {
        match self.revision {
            // rmcp's default: every revision the SDK knows. Kept verbatim so
            // the legacy surface negotiates exactly as it did before this
            // method existed — narrowing it is a change to what `initialize`
            // may agree to, and belongs to whoever needs it, not here.
            ServedRevision::V2025_11_25 => Cow::Borrowed(ProtocolVersion::KNOWN_VERSIONS),
            // The stateless surface advertises only itself. This is not
            // cosmetic: the transport requires per-request protocol metadata
            // in this mode, and a client negotiated below `2026-07-28` does
            // not send it — so a version this list admitted would be a version
            // whose ordinary requests the transport then rejects.
            ServedRevision::V2026_07_28 => Cow::Owned(vec![ProtocolVersion::V_2026_07_28]),
        }
    }

    async fn discover(
        &self,
        _context: RequestContext<RoleServer>,
    ) -> Result<DiscoverResult, McpError> {
        // rmcp's default body, plus the caching hints its conservative
        // constructor leaves at "immediately stale, private". This result is
        // the same constant for every caller, so saying so is the honest hint
        // — and `server/discover` is the one call a client makes before it can
        // make any other, which is precisely where a reusable answer earns its
        // keep.
        Ok(self.cached(DiscoverResult::from_server_info(
            self.supported_protocol_versions().into_owned(),
            self.get_info(),
        )))
    }

    async fn call_tool(
        &self,
        request: CallToolRequestParams,
        context: RequestContext<RoleServer>,
    ) -> Result<CallToolResponse, McpError> {
        // `#[tool_handler]`'s own body, which it generates only when this
        // method is absent — written out so the result passes `identified`.
        let call = ToolCallContext::new(self, request, context);
        self.tool_router
            .call(call)
            .await
            .map(|response| self.identified(response))
    }

    async fn list_tools(
        &self,
        request: Option<PaginatedRequestParams>,
        _context: RequestContext<RoleServer>,
    ) -> Result<ListToolsResult, McpError> {
        self.tools_page(request.as_ref())
            .map(|result| self.identified(result))
    }

    async fn list_prompts(
        &self,
        request: Option<PaginatedRequestParams>,
        _context: RequestContext<RoleServer>,
    ) -> Result<ListPromptsResult, McpError> {
        self.prompts_page(request.as_ref())
            .map(|result| self.identified(result))
    }

    async fn get_prompt(
        &self,
        request: GetPromptRequestParams,
        context: RequestContext<RoleServer>,
    ) -> Result<GetPromptResponse, McpError> {
        self.prompt(request, context)
            .await
            .map(|response| self.identified(response))
    }

    async fn list_resources(
        &self,
        request: Option<PaginatedRequestParams>,
        _context: RequestContext<RoleServer>,
    ) -> Result<ListResourcesResult, McpError> {
        // rmcp 3.x added SEP-2322's `result_type` and SEP-2549's
        // `ttl_ms`/`cache_scope` to every list result. The pages are built
        // through rmcp's constructor rather than a literal: it sets
        // `result_type` to `COMPLETE` and rmcp's server handler *clears* that
        // field for peers that negotiated a pre-`2026-07-28` revision, so the
        // `2025-11-25` wire shape is unchanged while the type stays correct for
        // the newer revision. Setting the fields by hand would defeat that.
        self.resources_page(request.as_ref())
            .map(|result| self.identified(result))
    }

    async fn list_resource_templates(
        &self,
        request: Option<PaginatedRequestParams>,
        _context: RequestContext<RoleServer>,
    ) -> Result<ListResourceTemplatesResult, McpError> {
        self.templates_page(request.as_ref())
            .map(|result| self.identified(result))
    }

    async fn read_resource(
        &self,
        request: ReadResourceRequestParams,
        _context: RequestContext<RoleServer>,
    ) -> Result<ReadResourceResponse, McpError> {
        // MRTR (SEP-2322) turned this return into a union of Complete /
        // InputRequired. Nothing this server serves needs a second round trip
        // — the bodies are constants — so the only correct variant is
        // Complete, at either revision, and `.into()` is the single seam that
        // guarantees it: `From<ReadResourceResult>` constructs `Complete` and
        // nothing else. See `call_tool` for the same seam on the tools side.
        resources::read(&request.uri)
            .map(|result| self.identified(self.cached(result)).into())
            // Revision-aware: `2026-07-28` withdrew -32002 and named -32602 as
            // its replacement, so the code cannot be a constant here.
            .ok_or_else(|| self.revision.resource_not_found(&request.uri))
    }

    fn accepted_subscription_filter(
        &self,
        requested: &rmcp::model::SubscriptionFilter,
    ) -> Option<rmcp::model::SubscriptionFilter> {
        crate::subscriptions::accepted(self.revision, requested)
    }

    async fn listen(&self, context: rmcp::service::SubscriptionContext) -> Result<(), McpError> {
        crate::subscriptions::run(context).await
    }

    async fn subscribe(
        &self,
        request: SubscribeRequestParams,
        context: RequestContext<RoleServer>,
    ) -> Result<(), McpError> {
        // An immediate update notification acknowledges the subscription in
        // an observable way (the idiom rmcp's own notification example uses);
        // the spec leaves update timing to the server.
        if self.track_subscription(request.uri.clone()) {
            let _ = context
                .peer
                .notify_resource_updated(ResourceUpdatedNotificationParam::new(request.uri))
                .await;
        }
        Ok(())
    }

    async fn unsubscribe(
        &self,
        request: UnsubscribeRequestParams,
        _context: RequestContext<RoleServer>,
    ) -> Result<(), McpError> {
        self.untrack_subscription(&request.uri);
        Ok(())
    }

    // SEP-2577 deprecates Logging; `2025-11-25` still requires it.
    #[allow(deprecated)]
    async fn set_level(
        &self,
        request: SetLevelRequestParams,
        _context: RequestContext<RoleServer>,
    ) -> Result<(), McpError> {
        // `2026-07-28` removed the method, but rmcp still dispatches it; refuse
        // it as rmcp refuses `ping` there, rather than answer `{}` (no
        // `resultType`, no `serverInfo`).
        if self.revision.is_stateless() {
            return Err(McpError::method_not_found::<SetLevelRequestMethod>());
        }
        if let Ok(mut level) = self.log_level.lock() {
            *level = request.level;
        }
        Ok(())
    }

    async fn complete(
        &self,
        request: CompleteRequestParams,
        _context: RequestContext<RoleServer>,
    ) -> Result<CompleteResult, McpError> {
        // The completion-complete scenario's documented example: prefix
        // completion over arg1 of test_prompt_with_arguments. Anything else
        // completes to nothing — minimal support is explicitly conformant.
        const CANDIDATES: [&str; 3] = ["paris", "park", "party"];
        let values = match &request.r#ref {
            Reference::Prompt(prompt)
                if prompt.name == "test_prompt_with_arguments"
                    && request.argument.name == "arg1" =>
            {
                CANDIDATES
                    .iter()
                    .filter(|candidate| candidate.starts_with(&request.argument.value))
                    .map(ToString::to_string)
                    .collect()
            }
            // `Reference` became `#[non_exhaustive]` in rmcp 3.x. Completing
            // to nothing is the conformant answer for every reference this
            // server does not special-case, so the catch-all carries the same
            // meaning the explicit arms did — and a future variant inherits
            // it rather than breaking the build.
            _ => Vec::new(),
        };
        let completion = CompletionInfo::with_all_values(values).map_err(|message| {
            McpError::internal_error(
                "completion overflow",
                Some(serde_json::json!({ "message": message })),
            )
        })?;
        Ok(self.identified(CompleteResult::new(completion)))
    }
}

