//! The server type and its [`ServerHandler`] implementation.
//!
//! One rule governs `get_info`: **advertise only what is implemented.** A
//! conformance reference that claims a capability and then answers
//! `method not found` would fail the very suite it exists to pass, so the
//! capability set below grows commit-by-commit with the modules that
//! implement it — tools, resources (with subscriptions), prompts, logging,
//! and completions today.
//!
//! The same rule chooses the protocol revision. [`ServedRevision`] selects it
//! once, when the server is built: `2025-11-25` by default, `2026-07-28` when
//! asked. Everything the newer revision changes about what this handler
//! *answers* — the version it negotiates, the version list it advertises, the
//! SEP-2549 caching hints on cacheable results, `serverInfo` in every result's
//! `_meta` (the private `identity` module) — reads that one value, so the
//! default surface has no new branch to take and is unchanged byte for byte.
//! What the newer revision changes about how requests are *routed* (no
//! sessions, per-request `_meta` required) is the transport's business and
//! lives in [`crate::http`].
//!
//! All six cacheable operations are built here, and the four list operations
//! are paginated (the private `listing` module, over [`crate::pagination`]).
//! `tools/list` and `prompts/list` were once generated by rmcp's
//! `#[tool_handler]` and `#[prompt_handler]` macros, which serve every route
//! in one page; paging them meant writing both by hand, which also brought
//! them under this crate's caching hints rather than the macros' own.

// SEP-2577 forward-deprecates Roots, Sampling and Logging. They remain fully
// functional and REQUIRED on the `2025-11-25` surface this crate implements
// and the official suite exercises, so rmcp 3.x's deprecation attributes fire
// on correct code. Each use is allowed on the item or statement that makes it,
// never the module or the crate, so a *different* future deprecation still
// warns everywhere else. They retire when the `2025-11-25` surface does.
