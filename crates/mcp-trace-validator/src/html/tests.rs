#[test]
fn the_accounting_lists_every_other_clause_with_its_reason() {
    let page = page(SESSION);
    let (reports, _) = judged(SESSION);
    let totals = reports[0].totals;
    assert!(page.contains(&format!(
        "<span class=\"group-name\">Excluded</span><span class=\"count\">{}</span>",
        totals.excluded
    )));
    assert!(page.contains(&format!(
        "<span class=\"group-name\">Not observed</span><span class=\"count\">{}</span>",
        totals.not_observed
    )));
    let excluded = reports[0]
        .requirements
        .iter()
        .find(|row| row.exclusion.is_some())
        .unwrap();
    assert!(page.contains(&format!("<li id=\"{}\">", excluded.id)));
    assert!(page.contains(&format!(
        "<span class=\"reason\">{}</span>",
        super::Text(excluded.exclusion.as_deref().unwrap())
    )));
    assert!(
        page.contains("capability <code>"),
        "not-applicable rows name the capability"
    );
    // Every clause of the revision has one anchor on the page.
    for row in &reports[0].requirements {
        assert_eq!(
            page.matches(&format!(" id=\"{}\"", row.id)).count(),
            1,
            "{}",
            row.id
        );
    }
}

#[test]
fn the_policy_admits_exactly_the_inline_stylesheet_and_nothing_else() {
    let page = page(SESSION);
    let policy = format!(
        "content=\"default-src 'none'; style-src {}; base-uri 'none'; form-action 'none'\"",
        digest::csp_source(STYLE)
    );
    assert!(page.contains(&policy));
    assert!(page.contains(&format!("<style>{STYLE}</style>")));
    // The policy comes before the only element it governs.
    assert!(page.find("Content-Security-Policy") < page.find("<style>"));
    assert_eq!(page.matches("<style>").count(), 1);
    for fetching in [
        "<script",
        "<link",
        "<img",
        "<iframe",
        "@import",
        "url(",
        " style=\"",
        " src=",
    ] {
        assert!(!page.contains(fetching), "{fetching}");
    }
}

#[test]
fn trace_text_renders_inert() {
    let hostile = r#"{"seq":0,"direction":"client-to-server","transport":"stdio","kind":"message","payload":{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-11-25","capabilities":{},"clientInfo":{"name":"<script>alert(1)</script>","version":"\"><img src=x onerror=alert(2)>"}}}}
{"seq":1,"direction":"server-to-client","transport":"stdio","kind":"message","payload":{"jsonrpc":"2.0","id":1,"result":{"protocolVersion":"2025-11-25","capabilities":{},"serverInfo":{"name":"s","version":"0"}}}}
{"seq":2,"direction":"client-to-server","transport":"stdio","kind":"message","payload":{"jsonrpc":"2.0","method":"notifications/initialized"}}
{"seq":3,"direction":"client-to-server","transport":"stdio","kind":"message","payload":{"jsonrpc":"2.0","id":"<script>alert(3)</script>","method":"\"><img src=x onerror=alert(4)><script>alert(5)</script>"}}
{"seq":4,"direction":"client-to-server","transport":"streamable-http","kind":"http","method":"POST","headers":{"mcp-session-id":"</code><script>alert(6)</script>"}}
"#;
    let (reports, events) = judged(hostile);
    let page = render(
        &reports,
        Trace {
            name: Some("<script>alert(7)</script>.jsonl"),
            events: &events,
        },
    );
    // The method is judged unknown, so it reaches findings as well as the
    // timeline: every route trace text takes onto the page is covered.
    assert!(reports[0].has_errors(), "the hostile method is a finding");
    assert!(page.contains("<span>mixed transports</span>"));
    for live in ["<script", "<img", "onerror=alert(4)>"] {
        assert!(!page.contains(live), "{live} reached the page unescaped");
    }
    assert!(page.contains("&lt;script&gt;alert(1)&lt;/script&gt;"));
    assert!(page.contains(
        "&quot;&gt;&lt;img src=x onerror=alert(4)&gt;&lt;script&gt;alert(5)&lt;/script&gt;"
    ));
    assert!(page.contains("&lt;/code&gt;&lt;script&gt;alert(6)&lt;/script&gt;"));
    assert!(
        page.contains("<h1 class=\"trace-name\">&lt;script&gt;alert(7)&lt;/script&gt;.jsonl</h1>")
    );
}

