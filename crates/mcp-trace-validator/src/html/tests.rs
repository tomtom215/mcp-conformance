#[test]
fn a_clause_this_build_cannot_judge_names_its_missing_checks() {
    let (mut reports, events) = judged(SESSION);
    let report = &mut reports[0];
    let row = report
        .requirements
        .iter_mut()
        .find(|row| row.outcome == crate::report::Outcome::Pass)
        .unwrap();
    row.outcome = crate::report::Outcome::Unsupported;
    row.missing_checks = vec!["future.check".to_owned()];
    let id = row.id.clone();
    report.totals.pass -= 1;
    report.totals.unsupported += 1;
    let page = render(
        &reports,
        Trace {
            name: None,
            events: &events,
        },
    );
    assert!(page.contains(&format!(
        "<article class=\"clause o-unsupported\" id=\"{id}\">"
    )));
    assert!(page.contains("checks this clause names: <code>future.check</code>."));
    assert!(page.contains("<span class=\"badge v-unsupported\">Unsupported</span>"));
    assert!(page.contains(
        "<span class=\"verdict-why\">1 clause failed and 1 clause needs a check this build lacks</span>"
    ));
}

#[test]
fn the_verdict_sentence_names_every_cause() {
    let (mut reports, events) = judged(SESSION);
    reports[0].totals.warn = 2;
    reports[0].totals.fail = 2;
    let page = render(
        &reports,
        Trace {
            name: None,
            events: &events,
        },
    );
    assert!(
        page.contains("<span class=\"verdict-why\">2 clauses failed and 2 clauses warned</span>")
    );
    reports[0].totals.unsupported = 2;
    let page = render(
        &reports,
        Trace {
            name: None,
            events: &events,
        },
    );
    assert!(
        page.contains(
            "2 clauses failed, 2 clauses warned and 2 clauses need checks this build lacks"
        )
    );
}
