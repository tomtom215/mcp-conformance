/// A complete `2025-11-25` session, then a `tools/list` request reusing id 1
/// (BASE-003 fails at seq 3) that the server answers at seq 4.
const SESSION: &str = r#"{"seq":0,"direction":"client-to-server","transport":"stdio","kind":"message","payload":{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-11-25","capabilities":{},"clientInfo":{"name":"c","version":"0"}}}}
{"seq":1,"direction":"server-to-client","transport":"stdio","kind":"message","payload":{"jsonrpc":"2.0","id":1,"result":{"protocolVersion":"2025-11-25","capabilities":{"tools":{}},"serverInfo":{"name":"s","version":"0"}}}}
{"seq":2,"direction":"client-to-server","transport":"stdio","kind":"message","payload":{"jsonrpc":"2.0","method":"notifications/initialized"}}
{"seq":3,"direction":"client-to-server","transport":"stdio","kind":"message","payload":{"jsonrpc":"2.0","id":1,"method":"tools/list"}}
{"seq":4,"direction":"server-to-client","transport":"stdio","kind":"message","payload":{"jsonrpc":"2.0","id":1,"result":{"tools":[]}}}
"#;

fn judged(document: &str) -> (Vec<Report>, Vec<TraceEvent>) {
    let judgment = judge::judge(document).unwrap();
    (judgment.reports, judgment.events)
}

fn page(document: &str) -> String {
    let (reports, events) = judged(document);
    render(
        &reports,
        Trace {
            name: Some("session.jsonl"),
            events: &events,
        },
    )
}

#[test]
fn the_page_names_the_trace_its_verdict_and_every_count() {
    let page = page(SESSION);
    assert!(page.starts_with("<!DOCTYPE html>\n<html lang=\"en\">"));
    assert!(page.ends_with("</html>\n"));
    assert!(page.contains("<title>Fail — session.jsonl — MCP trace validation</title>"));
    assert!(page.contains("<h1 class=\"trace-name\">session.jsonl</h1>"));
    assert!(page.contains("<span class=\"badge v-fail\">Fail</span>"));
    assert!(page.contains("revision <strong>2025-11-25</strong> (declared by the trace)"));
    assert!(page.contains("<span>5 events</span><span>stdio</span>"));
    for label in [
        "pass",
        "fail",
        "warn",
        "excluded",
        "unsupported",
        "not applicable",
        "not observed",
    ] {
        assert!(page.contains(&format!("<dt>{label}</dt>")), "{label}");
    }
    assert!(page.contains("<div class=\"t-fail\"><dt>fail</dt><dd>1</dd></div>"));
    assert!(page.contains("<div class=\"t-warn zero\"><dt>warn</dt><dd>0</dd></div>"));
    assert!(page.contains("Wire schema: pass (5 messages valid)"));
    assert!(page.contains(&format!(
        "Generated by mcp-trace-validator {}.",
        env!("CARGO_PKG_VERSION")
    )));
}

#[test]
fn a_failing_clause_shows_its_quote_link_and_findings_linked_to_events() {
    let page = page(SESSION);
    assert!(page.contains("<article class=\"clause o-fail\" id=\"BASE-003\">"));
    assert!(page.contains("<h3 class=\"clause-id\"><a href=\"#BASE-003\">BASE-003</a></h3>"));
    assert!(page.contains("<span class=\"pill level\">MUST</span>"));
    assert!(page.contains("<blockquote class=\"quote\"><p>"));
    assert!(page.contains("class=\"spec-link\" href=\"https://modelcontextprotocol.io/"));
    // The finding links to its event, and the event links back to the finding.
    assert!(page.contains("<li id=\"BASE-003-1\"><a class=\"seq\" href=\"#e3\">seq 3</a>"));
    assert!(page.contains("<li class=\"ev c2s flagged\" id=\"e3\">"));
    assert!(page.contains("<li class=\"o-fail\"><a href=\"#BASE-003-1\">BASE-003</a>"));
    // An event a finding names opens its payload; the others stay closed.
    assert!(page.contains("<details class=\"payload\" open>"));
    assert_eq!(page.matches("<details class=\"payload\">").count(), 4);
}

