#[test]
fn several_revisions_get_a_card_each_and_qualified_anchors() {
    let options = Options::default()
        .revisions(["2025-11-25".parse().unwrap(), "2026-07-28".parse().unwrap()]);
    let judgment = judge::judge_with(SESSION, &options).unwrap();
    let page = render(
        &judgment.reports,
        Trace {
            name: Some("s.jsonl"),
            events: &judgment.events,
        },
    );
    assert!(page.contains("revisions <strong>2025-11-25, 2026-07-28</strong> (requested)"));
    assert!(page.contains("the most severe of 2 revisions"));
    assert_eq!(page.matches("<section class=\"revision ").count(), 2);
    assert!(page.contains("<h3 class=\"revision-heading\">At revision 2026-07-28</h3>"));
    assert!(page.contains("id=\"2025-11-25-BASE-003\""));
    assert!(page.contains("<h4 class=\"clause-id\">"));
    // A timeline finding says which revision it was judged at.
    assert!(page.contains(
        "<a href=\"#2025-11-25-BASE-003-1\">BASE-003</a><span class=\"pill rev\">2025-11-25</span>"
    ));
    // The session declares 2025-11-25 only, so the other column is flagged.
    assert!(page.contains("This session declares protocol revision 2025-11-25, not 2026-07-28"));
}

#[test]
fn a_run_lists_every_trace_and_why_one_was_not_judged() {
    let (reports, events) = judged(SESSION);
    let trace = |name| Trace {
        name: Some(name),
        events: &events,
    };
    let unjudged = [Unjudged::new("broken.jsonl", "malformed trace: <line 2>")];
    let page = render_run(
        &[
            (trace("a.jsonl"), &reports[..]),
            (trace("b.jsonl"), &reports[..]),
        ],
        &unjudged,
    );
    assert!(page.contains("<h1>3 traces</h1>"));
    assert!(
        page.contains("<section class=\"panel verdict v-incomplete\" aria-label=\"Run verdict\">")
    );
    assert!(
        page.contains(
            "<li><a href=\"#t0\">a.jsonl</a><span class=\"badge v-fail\">Fail</span></li>"
        )
    );
    assert!(
        page.contains("<p class=\"unjudged-why\">Not judged: malformed trace: &lt;line 2&gt;</p>")
    );
    // Each trace's anchors live in its own namespace.
    assert!(page.contains("<section class=\"trace\" id=\"t1\" aria-labelledby=\"t1-title\">"));
    assert!(page.contains("id=\"t0-BASE-003\"") && page.contains("id=\"t1-BASE-003\""));
    assert!(page.contains("href=\"#t1-e3\""));
    assert!(page.contains("<h3 id=\"t0-findings-h\">Clauses to act on</h3>"));
    // Without an unjudged trace, the run's verdict is its worst trace's.
    let complete = render_run(&[(trace("a.jsonl"), &reports[..])], &[]);
    assert!(
        complete.contains("<h1 class=\"trace-name\">a.jsonl</h1>"),
        "one trace is a plain page"
    );
    let pair_run = render_run(
        &[
            (trace("a.jsonl"), &reports[..]),
            (trace("b.jsonl"), &reports[..]),
        ],
        &[],
    );
    assert!(
        pair_run.contains("<section class=\"panel verdict v-fail\" aria-label=\"Run verdict\">")
    );
    assert!(render_run(&[], &[]).contains("<h1>0 traces</h1>"));
}

#[test]
fn http_and_lifecycle_events_say_what_they_were() {
    let document = r#"{"seq":0,"direction":"client-to-server","transport":"streamable-http","kind":"http","method":"POST","headers":{"content-type":"application/json"}}
{"seq":1,"direction":"client-to-server","transport":"streamable-http","kind":"message","payload":{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-11-25","capabilities":{},"clientInfo":{"name":"c","version":"0"}}},"ts":"2026-10-13T00:00:00Z"}
{"seq":2,"direction":"server-to-client","transport":"streamable-http","kind":"http","status":200}
{"seq":3,"direction":"server-to-client","transport":"streamable-http","kind":"message","payload":{"jsonrpc":"2.0","id":1,"result":{"protocolVersion":"2025-11-25","capabilities":{},"serverInfo":{"name":"s","version":"0"}}}}
{"seq":4,"direction":"server-to-client","transport":"streamable-http","kind":"http"}
{"seq":5,"direction":"server-to-client","transport":"streamable-http","kind":"lifecycle","event":"transport-close"}
{"seq":6,"direction":"server-to-client","transport":"streamable-http","kind":"lifecycle","event":"transport-abort"}
{"seq":7,"direction":"client-to-server","transport":"streamable-http","kind":"lifecycle","event":"transport-open"}
"#;
    let page = page(document);
    assert!(page.contains(
        "<span class=\"kind k-http\">HTTP request</span><code class=\"method\">POST</code>"
    ));
    assert!(page.contains(
        "<span class=\"kind k-http\">HTTP response</span><code class=\"method\">200</code>"
    ));
    assert!(page.contains("<span class=\"kind k-http\">HTTP</span>"));
    assert!(page.contains("<dt>content-type</dt><dd>application/json</dd>"));
    assert!(page.contains("Headers <span class=\"count\">1</span>"));
    for what in ["transport closed", "transport aborted", "transport opened"] {
        assert!(
            page.contains(&format!("<span class=\"kind k-life\">{what}</span>")),
            "{what}"
        );
    }
    assert!(page.contains("<span class=\"ev-ts\">2026-10-13T00:00:00Z</span>"));
    assert!(page.contains("<span>Streamable HTTP</span>"));
}

