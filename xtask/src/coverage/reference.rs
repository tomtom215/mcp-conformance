//! The book's requirement reference: one generated page per built-in revision,
//! listing every clause with its level, the party it binds, its verbatim quote,
//! a link to the published text, and either the checks that judge it or the
//! reason no recorded trace can.
//!
//! A report names a clause by ID (`BASE-003`), and before these pages a reader
//! had to find the ID in a registry JSON file to learn more than the report
//! printed — in particular *why* an excluded clause is excluded, which is the
//! question an exclusion invites. The pages are a projection of the registry,
//! like the README's coverage table: `cargo xtask coverage` writes them and
//! `--check` fails when the committed pages differ from what the registry
//! renders to, so they cannot drift.

use core::fmt::Write as _;
use std::path::PathBuf;

use mcp_conformance_core::requirement::{Actor, Registry, RegistrySet, Requirement, Verification};
use mcp_conformance_core::revision::ProtocolRevision;

/// Where the pages live, relative to the book's `src/`.
pub(super) const DIR: &str = "reference";

/// Each built-in revision's page, newest first, then the page of the
/// extensions attached to each revision that has any: `(path under book/src,
/// text)`.
pub(super) fn render_all(set: &RegistrySet) -> Option<Vec<(PathBuf, String)>> {
    let mut revisions = set.revisions().to_vec();
    revisions.sort_unstable_by(|a, b| b.cmp(a));
    let mut pages = Vec::new();
    for revision in &revisions {
        let registry = set.registry(*revision)?;
        pages.push((page_path(*revision), render(*revision, &registry)));
    }
    for revision in &revisions {
        let registry = set.registry(*revision)?;
        if !registry.extension_requirements().is_empty() {
            pages.push((
                extensions_page_path(*revision),
                render_extensions(*revision, &registry),
            ));
        }
    }
    Some(pages)
}

/// `reference/extensions-2026-07-28.md`, relative to the book's `src/`.
pub(super) fn extensions_page_path(revision: ProtocolRevision) -> PathBuf {
    PathBuf::from(DIR).join(format!("extensions-{revision}.md"))
}

/// The extensions attached to `revision`: a section per extension, each entry
/// as a revision's page writes it.
fn render_extensions(revision: ProtocolRevision, registry: &Registry) -> String {
    let mut out = String::new();
    out.push_str(
        "<!-- SPDX-License-Identifier: MIT -->\n\
         <!-- Copyright 2026 Tom F. (https://github.com/tomtom215) -->\n\
         <!-- Generated by `cargo xtask coverage` from the registry; do not edit by hand. -->\n\n",
    );
    let _ = writeln!(out, "# Extensions — `{revision}`\n");
    let total = registry.extension_requirements().len();
    let checked = registry
        .extension_requirements()
        .iter()
        .filter(|requirement| matches!(requirement.verification, Verification::Checks { .. }))
        .count();
    let _ = writeln!(
        out,
        "The clauses of the official extensions attached to `{revision}` — {total} in all, \
         {checked} judged from a recorded trace and {excluded} excluded with the reason below. \
         An extension is optional by definition, so its clauses never change a report's verdict \
         or exit status: a report lists them under `extensions`, each extension with a verdict \
         of its own, the way the official suite runs an extension's scenarios under \
         `not_scored: extension` \
         ([ADR-0023](https://github.com/tomtom215/mcp-conformance/blob/main/docs/plan/decisions/0023-extensions-are-reported-never-scored.md)). \
         Each entry quotes the extension's own specification and links to where its repository \
         publishes it.\n",
        excluded = total - checked,
    );
    let mut extension = "";
    for requirement in registry.extension_requirements() {
        let this = requirement.extension.as_deref().unwrap_or_default();
        if this != extension {
            extension = this;
            let _ = writeln!(out, "## `{extension}`\n");
        }
        entry(&mut out, revision, requirement);
    }
    out
}

/// `reference/requirements-2026-07-28.md`, relative to the book's `src/`.
pub(super) fn page_path(revision: ProtocolRevision) -> PathBuf {
    PathBuf::from(DIR).join(format!("requirements-{revision}.md"))
}

fn render(revision: ProtocolRevision, registry: &Registry) -> String {
    let mut out = String::new();
    out.push_str(
        "<!-- SPDX-License-Identifier: MIT -->\n\
         <!-- Copyright 2026 Tom F. (https://github.com/tomtom215) -->\n\
         <!-- Generated by `cargo xtask coverage` from the registry; do not edit by hand. -->\n\n",
    );
    let _ = writeln!(out, "# Requirements — `{revision}`\n");
    let total = registry.requirements().len();
    let checked = registry
        .requirements()
        .iter()
        .filter(|requirement| matches!(requirement.verification, Verification::Checks { .. }))
        .count();
    let _ = writeln!(
        out,
        "Every normative clause of the `{revision}` specification that the validator's \
         registry carries — {total} in all, {checked} judged from a recorded trace and \
         {excluded} excluded with the reason below. A report names a clause by the ID \
         used as each heading here; each entry quotes the specification verbatim and \
         links to the published text. `mcp-trace-validator requirements --revision \
         {revision} --format json` prints the same data as JSON.\n",
        excluded = total - checked,
    );

    let mut area = "";
    for requirement in registry.requirements() {
        let this_area = requirement.id.area();
        if this_area != area {
            area = this_area;
            let _ = writeln!(out, "## {area}\n");
        }
        entry(&mut out, revision, requirement);
    }
    out
}

/// One requirement's entry: heading, level and party, quote, link, verdict line.
fn entry(out: &mut String, revision: ProtocolRevision, requirement: &Requirement) {
    let _ = writeln!(out, "### {}\n", requirement.id.as_str());
    let party = match requirement.actor {
        Actor::Server => "server",
        Actor::Client => "client",
        Actor::Both => "client and server",
        // `Actor` is #[non_exhaustive]; a party this build cannot name is
        // rendered as such rather than guessed.
        _ => "unnamed party",
    };
    let _ = write!(
        out,
        "**{}** · binds the {party}",
        requirement.level.keyword()
    );
    if let Some(gate) = &requirement.capability {
        let _ = write!(out, " · only once `{}` is negotiated", gate.as_str());
    }
    out.push_str("\n\n");
    let _ = writeln!(out, "> {}\n", requirement.source.quote);
    let _ = writeln!(
        out,
        "[`{}`]({})\n",
        requirement.source.section,
        requirement.url(revision)
    );
    match &requirement.verification {
        Verification::Checks { checks } => {
            let names: Vec<String> = checks.iter().map(|check| format!("`{check}`")).collect();
            let _ = writeln!(out, "Judged by {}.\n", names.join(", "));
        }
        Verification::Excluded { exclusion } => {
            let _ = writeln!(out, "**Excluded.** {exclusion}\n");
        }
        _ => out.push_str("Verification of a kind this build cannot describe.\n\n"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn builtin() -> RegistrySet {
        RegistrySet::builtin().unwrap_or_else(|error| panic!("{error}"))
    }

    #[test]
    fn there_is_one_page_per_builtin_revision_newest_first_then_the_extensions() {
        let pages = render_all(&builtin()).unwrap_or_default();
        let paths: Vec<&PathBuf> = pages.iter().map(|(path, _)| path).collect();
        // Compared as paths, not as display strings: Windows separates with `\`.
        let reference = PathBuf::from("reference");
        assert_eq!(
            paths,
            [
                &reference.join("requirements-2026-07-28.md"),
                &reference.join("requirements-2025-11-25.md"),
                &reference.join("extensions-2026-07-28.md")
            ]
        );
    }

    #[test]
    fn every_requirement_has_a_heading_its_quote_and_one_verdict_line() {
        let set = builtin();
        for revision in set.revisions() {
            let registry = set
                .registry(*revision)
                .unwrap_or_else(|| panic!("{revision}"));
            let page = render(*revision, &registry);
            for requirement in registry.requirements() {
                let heading = format!("\n### {}\n", requirement.id.as_str());
                let at = page
                    .find(&heading)
                    .unwrap_or_else(|| panic!("{revision}: no {heading}"));
                let rest = &page[at + heading.len()..];
                let entry = &rest[..rest.find("\n### ").unwrap_or(rest.len())];
                assert!(
                    entry.contains(&requirement.source.quote),
                    "{revision} {}",
                    requirement.id.as_str()
                );
                assert!(
                    entry.contains(&requirement.source.url(*revision)),
                    "{entry}"
                );
                let verdicts =
                    entry.matches("Judged by ").count() + entry.matches("**Excluded.**").count();
                assert_eq!(verdicts, 1, "{entry}");
            }
        }
    }

    #[test]
    fn a_gated_clause_names_its_gate_and_an_excluded_one_its_reason() {
        let set = builtin();
        let older = set
            .registry("2025-11-25".parse().unwrap_or_else(|e| panic!("{e:?}")))
            .unwrap_or_else(|| panic!("2025-11-25"));
        let page = render(
            "2025-11-25".parse().unwrap_or_else(|e| panic!("{e:?}")),
            &older,
        );
        let gated = older
            .requirements()
            .iter()
            .find(|r| r.capability.is_some())
            .unwrap_or_else(|| panic!("no gated clause"));
        let gate = gated
            .capability
            .as_ref()
            .map(|g| g.as_str().to_owned())
            .unwrap_or_default();
        assert!(
            page.contains(&format!("only once `{gate}` is negotiated")),
            "{gate}"
        );
        let excluded = older
            .requirements()
            .iter()
            .find_map(|r| match &r.verification {
                Verification::Excluded { exclusion } => Some(exclusion.clone()),
                _ => None,
            })
            .unwrap_or_default();
        assert!(page.contains(&format!("**Excluded.** {excluded}")));
    }
}
