/// A table cell: one line, pipes escaped.
fn cell(text: &str) -> String {
    text.replace('\n', " ").replace('|', "\\|")
}

fn code_list(items: &[&str]) -> String {
    if items.is_empty() {
        return "—".to_owned();
    }
    items
        .iter()
        .map(|item| format!("`{item}`"))
        .collect::<Vec<_>>()
        .join(", ")
}

/// The whole page.
pub(crate) fn page(inputs: &Inputs) -> String {
    let comparisons: Vec<Comparison<'_>> = inputs
        .results
        .traces
        .iter()
        .map(|trace| compare(trace, &inputs.rules.rules))
        .collect();
    let mut out = String::new();
    head(&mut out, inputs);
    summary(&mut out, &comparisons);
    divergences(&mut out, inputs, &comparisons);
    recorded(&mut out, inputs);
    issues(&mut out, inputs);
    rule_map(&mut out, inputs, &comparisons);
    every_trace(&mut out, &comparisons);
    out
}

fn head(out: &mut String, inputs: &Inputs) {
    let traces = inputs.results.traces.len();
    let _ = write!(
        out,
        "<!-- SPDX-License-Identifier: MIT -->\n<!-- Copyright 2026 Tom F. (https://github.com/tomtom215) -->\n\n\
<!-- Generated by `cargo xtask mcpsnoop` from conformance/mcpsnoop/{{results,rules,triage}}.json.\n     \
`cargo xtask mcpsnoop --check` (part of `cargo xtask gates`) fails on any hand edit. -->\n\n\
# A second opinion: mcpsnoop\n\n\
[`mcpsnoop`](https://github.com/kerlenton/mcpsnoop) is the one other tool that judges a recorded MCP \
session offline: `mcpsnoop check` reads a capture and fails on a fixed set of rules. The official suite \
calibrates this project against live scenarios; mcpsnoop calibrates it against a reader of recordings, \
which is what this project is. This page is that comparison over all {traces} corpus traces, with every \
disagreement triaged: which tool is right, by which clause, and what was done about it.\n\n\
## How the comparison is made\n\n\
**The binary.** mcpsnoop `{PINNED}`, the current npm release when measured, taken from the npm \
registry and never built from source. The `mcpsnoop` package is a launcher with no install script; the \
Go binary ships in a per-platform package. Both tarballs were fetched with `npm pack` and checked \
against the registry's `integrity`:\n\n"
    );
    for (package, integrity) in TARBALLS {
        let _ = writeln!(out, "- `{package}` — `{integrity}`");
    }
    let _ = write!(
        out,
        "\nThe binary inside, `package/bin/mcpsnoop`, has SHA-256 `{BINARY_SHA256}`. To measure, \
point `MCPSNOOP` at it and run `cargo xtask mcpsnoop`; without it the task skips loudly. mcpsnoop is \
never a gate on a pull request — a scheduled, informational job re-measures it.\n\n\
**The same session in front of both.** Our traces are converted into the capture format mcpsnoop \
writes itself (`xtask/src/mcpsnoop/convert.rs`). On stdio the conversion is lossless. On HTTP a frame \
gets the headers, status and exchange the trace's own order settles — the rules our validator's framing \
applies — and no more; a frame whose context the trace cannot settle is marked unframed, and a finding \
that reads such context there is set aside, not counted. The conversion is checked against mcpsnoop's \
own recordings on every measurement: sessions recorded through both tools at once — the reference host \
against the everything server, committed under `conformance/mcpsnoop/native/` — must draw the same \
mcpsnoop findings from the converted trace as from mcpsnoop's capture once that capture's frames share \
one connection, the single field the conversion fixes rather than carries. {}\n\n\
**What is compared.** mcpsnoop's conformance signals — `invalid`, `warn` and `mismatch`, the three its \
own rule descriptions call protocol violations — against our `fail` and `warn` rows and the wire schema. \
Its other signals (a call that ended in an error, one still pending when the capture ended, a deprecated \
feature) are counted per trace but say nothing about conformance. Each mcpsnoop rule is mapped to the \
registry clauses its condition violates, read from both texts (`conformance/mcpsnoop/rules.json`, \
tabulated below); a mapping is *partial* where the rule checks only part of the clause. Then, per \
trace: a fired rule one of whose clauses we flag is **agreement**; a fired rule none of whose clauses we \
flag is a **mcpsnoop-only** divergence; a clause we flag that a rule maps fully, with that rule silent, \
is an **ours-only** divergence; a clause we flag that no rule maps fully is **beyond mcpsnoop**, a \
difference of scope rather than of reading.\n\n",
        native_sentence(inputs)
    );
}

/// What the native recordings showed, counted.
fn native_sentence(inputs: &Inputs) -> String {
    let native = &inputs.results.native;
    let same = native.iter().filter(|check| check.same_as_native).count();
    let sessions: Vec<String> = native
        .iter()
        .map(|check| format!("`{}` ({} findings)", check.session, check.findings))
        .collect();
    format!(
        "In the committed run {same} of {} such sessions did: {}.",
        native.len(),
        sessions.join(", ")
    )
}

fn summary(out: &mut String, comparisons: &[Comparison<'_>]) {
    let _ = write!(
        out,
        "## Summary\n\n| Corpus directory | Traces |\n|---|---:|\n"
    );
    for directory in DIRECTORIES {
        let count = comparisons
            .iter()
            .filter(|comparison| directory_of(comparison.trace) == directory)
            .count();
        let _ = writeln!(out, "| `corpus/{directory}/` | {count} |");
    }
    let mut matrix = [[0_usize; 2]; 2];
    let mut categories: BTreeMap<Category, usize> = BTreeMap::new();
    for comparison in comparisons {
        let ours = usize::from(comparison.trace.ours.verdict != "fail");
        let snoop = usize::from(!comparison.snoop_fails());
        matrix[ours][snoop] += 1;
        *categories.entry(comparison.category()).or_default() += 1;
    }
    let set_aside: usize = comparisons
        .iter()
        .filter(|comparison| !comparison.set_aside.is_empty())
        .count();
    let beyond: std::collections::BTreeSet<(&str, &str)> = comparisons
        .iter()
        .flat_map(|comparison| {
            comparison
                .beyond
                .iter()
                .map(|id| (comparison.trace.revision.as_str(), *id))
        })
        .collect();
    let _ = write!(
        out,
        "\nVerdicts, ours against mcpsnoop's conformance signals:\n\n\
| | mcpsnoop flags the trace | mcpsnoop does not |\n|---|---:|---:|\n\
| our verdict `fail` | {} | {} |\n| our verdict `pass` or `pass-with-warnings` | {} | {} |\n\n\
Traces by how the two readings relate:\n\n| Relation | Traces |\n|---|---:|\n",
        matrix[0][0], matrix[0][1], matrix[1][0], matrix[1][1]
    );
    for (category, count) in &categories {
        let _ = writeln!(out, "| {} | {count} |", category.label());
    }
    let _ = write!(
        out,
        "\nmcpsnoop flagging less than we do is mostly scope, not disagreement: its rules cover a part of \
the registry, and the traces it passes while we fail are the *beyond mcpsnoop* row. Across the corpus \
we flag {} distinct clauses (counted per revision) that no mcpsnoop rule maps fully. Findings were set \
aside for reading HTTP context the conversion could not supply on {set_aside} traces.\n\n",
        beyond.len()
    );
}

fn directory_of(trace: &TraceResult) -> &str {
    trace
        .trace
        .rsplit_once('/')
        .map_or("", |(directory, _)| directory)
}

fn divergences(out: &mut String, inputs: &Inputs, comparisons: &[Comparison<'_>]) {
    let _ = write!(
        out,
        "## Divergences\n\nEvery divergence the run shows, and its triage (`conformance/mcpsnoop/triage.json`). \
`--check` fails while any divergence is untriaged or any triage entry matches nothing.\n\n\
| # | Kind | Subject | Traces | Class | Right | Resolution |\n|---:|---|---|---|---|---|---|\n"
    );
    let triage = &inputs.triage.divergences;
    for (index, entry) in triage.iter().enumerate() {
        let traces: Vec<&str> = entry.traces.iter().map(String::as_str).collect();
        let _ = writeln!(
            out,
            "| {} | {} | `{}` | {} | {} | {} | {} |",
            index + 1,
            entry.kind,
            entry.subject,
            code_list(&traces),
            entry.class,
            entry.right,
            cell(&entry.resolution)
        );
    }
    out.push('\n');
    for (index, entry) in triage.iter().enumerate() {
        let revision = comparisons
            .iter()
            .find(|comparison| entry.traces.contains(&comparison.trace.trace))
            .map_or("", |comparison| comparison.trace.revision.as_str());
        let _ = write!(
            out,
            "### {}. `{}` ({})\n\n{}\n\n",
            index + 1,
            entry.subject,
            entry.kind,
            entry.note
        );
        quotes(out, inputs, revision, &entry.quote);
        let _ = write!(out, "Resolution: {}\n\n", entry.resolution);
    }
}

fn quotes(out: &mut String, inputs: &Inputs, revision: &str, ids: &[String]) {
    for id in ids {
        let clause = inputs.quotes.get(revision, id).or_else(|| {
            inputs
                .quotes
                .revisions()
                .into_iter()
                .find_map(|other| inputs.quotes.get(other, id))
        });
        if let Some(clause) = clause {
            let _ = write!(
                out,
                "> **{id}** ({}): {} — [source]({})\n\n",
                clause.level, clause.quote, clause.url
            );
        }
    }
}

fn recorded(out: &mut String, inputs: &Inputs) {
    let _ = write!(
        out,
        "## Found on live recordings\n\nDivergences that only a session recorded by mcpsnoop itself shows, \
because they turn on something our trace format does not record.\n\n"
    );
    for entry in &inputs.triage.recorded {
        let evidence: Vec<String> = entry
            .evidence
            .iter()
            .map(|path| format!("`conformance/mcpsnoop/{path}`"))
            .collect();
        let _ = write!(
            out,
            "### `{}` — {}, right: {}\n\n{}\n\nEvidence: {}.\n\n",
            entry.rule,
            entry.class,
            entry.right,
            entry.note,
            evidence.join(", ")
        );
        quotes(out, inputs, "2025-11-25", &entry.quote);
        let _ = write!(out, "Resolution: {}\n\n", entry.resolution);
    }
}

fn issues(out: &mut String, inputs: &Inputs) {
    let _ = write!(
        out,
        "## Upstream issue drafts\n\nWritten for mcpsnoop's tracker and **not filed**: filing is the \
owner's call.\n\n"
    );
    for issue in &inputs.triage.issues {
        let _ = write!(
            out,
            "### `{}`: {}\n\n{}\n\n",
            issue.id,
            issue.title,
            issue.body.trim_end()
        );
    }
}

fn rule_map(out: &mut String, inputs: &Inputs, comparisons: &[Comparison<'_>]) {
    let _ = write!(
        out,
        "## The rule map\n\nEach mcpsnoop rule, the message template that identifies it (`*` is any run), \
and the clauses it corresponds to; *italic* ids are partial. Fired counts traces where the rule \
fired and was not set aside. A rule no trace fires was read from the binary's strings and is untested \
here.\n\n| Rule | Template | `2025-11-25` | `2026-07-28` | Context | Fired | Reading |\n\
|---|---|---|---|---|---:|---|\n"
    );
    for rule in &inputs.rules.rules {
        let fired = comparisons
            .iter()
            .filter(|comparison| comparison.fired.contains_key(rule.id.as_str()))
            .count();
        let maps = |revision: &str| {
            let ids = rule.maps.get(revision).map_or(&[][..], Vec::as_slice);
            if ids.is_empty() {
                return "—".to_owned();
            }
            ids.iter()
                .map(|id| {
                    if rule.partial.contains(id) {
                        format!("*{id}*")
                    } else {
                        id.clone()
                    }
                })
                .collect::<Vec<_>>()
                .join(", ")
        };
        let templates: Vec<String> = rule
            .templates
            .iter()
            .map(|template| format!("`{}`", cell(template)))
            .collect();
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} | {} | {fired} | {} |",
            rule.id,
            templates.join("<br>"),
            maps("2025-11-25"),
            maps("2026-07-28"),
            rule.context.as_deref().unwrap_or("body"),
            cell(&rule.reading)
        );
    }
    out.push('\n');
}

fn every_trace(out: &mut String, comparisons: &[Comparison<'_>]) {
    let _ = write!(
        out,
        "## Every trace\n\n| Trace | Revision | Ours | We flag | mcpsnoop | Rules fired | Set aside | Relation |\n\
|---|---|---|---|---|---|---|---|\n"
    );
    for comparison in comparisons {
        let trace = comparison.trace;
        let flagged: Vec<&str> = trace.ours.flagged.iter().map(String::as_str).collect();
        let fired: Vec<&str> = comparison.fired.keys().copied().collect();
        let set_aside: Vec<&str> = comparison.set_aside.iter().copied().collect();
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} | {} | {} | {} | {} |",
            trace.trace,
            trace.revision,
            trace.ours.verdict,
            code_list(&flagged),
            if comparison.snoop_fails() {
                "flags"
            } else {
                "silent"
            },
            code_list(&fired),
            code_list(&set_aside),
            comparison.category().label()
        );
    }
}
