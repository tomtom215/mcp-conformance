//! The npm packages, as directories `npm pack` and `npm publish` take: the
//! main package `mcp-conformance`, whose `bin` entries are launchers
//! (`packaging/npm/launch.js`), and one `@mcp-conformance/<os>-<cpu>` package
//! per release target carrying that target's binaries. The main package names
//! every platform package as an optional dependency at exactly its own
//! version; npm installs the one whose `os` and `cpu` match the machine and
//! skips the rest. No package has an install script.

use serde_json::{Value, json};

use super::targets::{BINARIES, TARGETS, Target};
use super::{DESCRIPTION, HOMEPAGE, REPOSITORY};

/// The launcher every `bin` entry requires.
const LAUNCHER: &str = include_str!("../../../packaging/npm/launch.js");

/// One file of a package directory: its path inside the package, contents,
/// and whether it must be executable.
pub(crate) type File = (String, Vec<u8>, bool);

/// The fields both kinds of package share.
fn common(name: &str, version: &str, description: &str) -> serde_json::Map<String, Value> {
    json!({
        "name": name,
        "version": version,
        "description": description,
        "license": "MIT",
        "author": "Tom F.",
        "homepage": HOMEPAGE,
        "bugs": format!("{REPOSITORY}/issues"),
        // npm's provenance check requires this to name the repository whose
        // workflow publishes (release.yml), in this form.
        "repository": { "type": "git", "url": format!("git+{REPOSITORY}.git") },
    })
    .as_object()
    .cloned()
    .unwrap_or_default()
}

/// The main package's `package.json`.
pub(crate) fn main_manifest(version: &str) -> Value {
    let mut map = common("mcp-conformance", version, DESCRIPTION);
    map.insert(
        "keywords".to_owned(),
        json!([
            "mcp",
            "model-context-protocol",
            "conformance",
            "testing",
            "validator"
        ]),
    );
    let bins: serde_json::Map<String, Value> = BINARIES
        .iter()
        .map(|name| ((*name).to_owned(), json!(format!("bin/{name}.js"))))
        .collect();
    map.insert("bin".to_owned(), Value::Object(bins));
    map.insert("files".to_owned(), json!(["bin", "lib"]));
    map.insert("engines".to_owned(), json!({ "node": ">=18" }));
    let platforms: serde_json::Map<String, Value> = TARGETS
        .iter()
        .map(|target| (target.npm_package(), json!(version)))
        .collect();
    map.insert("optionalDependencies".to_owned(), Value::Object(platforms));
    Value::Object(map)
}

/// A platform package's `package.json`.
pub(crate) fn platform_manifest(target: Target, version: &str) -> Value {
    let description = format!(
        "The {} ({}) binaries of mcp-conformance; install the `mcp-conformance` package, \
         which selects this one",
        target.npm_key(),
        target.triple
    );
    let mut map = common(&target.npm_package(), version, &description);
    map.insert("os".to_owned(), json!([target.npm_os]));
    map.insert("cpu".to_owned(), json!([target.npm_cpu]));
    map.insert("files".to_owned(), json!(["bin"]));
    // Yarn PnP and similar must unpack it: binaries cannot run from a zip.
    map.insert("preferUnplugged".to_owned(), json!(true));
    // A scoped package is private on first publish unless this says otherwise.
    map.insert("publishConfig".to_owned(), json!({ "access": "public" }));
    Value::Object(map)
}

fn manifest_file(manifest: &Value) -> File {
    let mut text = serde_json::to_string_pretty(manifest).unwrap_or_default();
    text.push('\n');
    ("package.json".to_owned(), text.into_bytes(), false)
}

/// Every file of the main package.
pub(crate) fn main_files(version: &str, readme: &str, license: &[u8]) -> Vec<File> {
    let mut files = vec![
        manifest_file(&main_manifest(version)),
        ("README.md".to_owned(), readme.as_bytes().to_vec(), false),
        ("LICENSE".to_owned(), license.to_vec(), false),
        (
            "lib/launch.js".to_owned(),
            LAUNCHER.as_bytes().to_vec(),
            false,
        ),
    ];
    for name in BINARIES {
        let script = format!(
            "#!/usr/bin/env node\n\
             // SPDX-License-Identifier: MIT\n\
             // Generated by `cargo xtask packages`: runs this platform's {name} binary.\n\
             \"use strict\";\n\
             require(\"../lib/launch.js\").run(\"{name}\");\n"
        );
        files.push((format!("bin/{name}.js"), script.into_bytes(), true));
    }
    files
}

/// Every file of a platform package; `binaries` are `(name, bytes)` in
/// [`BINARIES`] order.
pub(crate) fn platform_files(
    target: Target,
    version: &str,
    license: &[u8],
    binaries: &[(&str, Vec<u8>)],
) -> Vec<File> {
    let readme = format!(
        "<!-- SPDX-License-Identifier: MIT -->\n\n# {}\n\nThe `{}` release binaries of \
         [mcp-conformance]({REPOSITORY}) {version}: {}.\n\nInstall `mcp-conformance` rather \
         than this package; it depends on this one where it fits the machine.\n",
        target.npm_package(),
        target.triple,
        BINARIES.join(", "),
    );
    let mut files = vec![
        manifest_file(&platform_manifest(target, version)),
        ("README.md".to_owned(), readme.into_bytes(), false),
        ("LICENSE".to_owned(), license.to_vec(), false),
    ];
    for (name, bytes) in binaries {
        files.push((format!("bin/{name}{}", target.exe()), bytes.clone(), true));
    }
    files
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn the_main_package_pins_every_platform_package_to_its_own_version() {
        let manifest = main_manifest("1.2.3-rc.1");
        assert_eq!(manifest["name"], "mcp-conformance");
        assert_eq!(manifest["version"], "1.2.3-rc.1");
        let optional = manifest["optionalDependencies"].as_object().unwrap();
        assert_eq!(optional.len(), TARGETS.len());
        for target in TARGETS {
            assert_eq!(
                optional[&target.npm_package()],
                "1.2.3-rc.1",
                "{}",
                target.triple
            );
        }
        let bins = manifest["bin"].as_object().unwrap();
        assert_eq!(bins.len(), 3);
        assert_eq!(bins["mcp-trace-validator"], "bin/mcp-trace-validator.js");
        assert!(manifest.get("scripts").is_none(), "no install scripts");
        assert_eq!(
            manifest["repository"]["url"],
            "git+https://github.com/tomtom215/mcp-conformance.git"
        );
    }

    #[test]
    fn a_platform_package_is_selected_by_os_and_cpu_and_carries_no_scripts() {
        let windows = TARGETS[4];
        let manifest = platform_manifest(windows, "0.6.0");
        assert_eq!(manifest["name"], "@mcp-conformance/win32-x64");
        assert_eq!(manifest["version"], "0.6.0");
        assert_eq!(manifest["os"], json!(["win32"]));
        assert_eq!(manifest["cpu"], json!(["x64"]));
        assert_eq!(manifest["publishConfig"]["access"], "public");
        assert!(manifest.get("scripts").is_none() && manifest.get("bin").is_none());
        let binaries: Vec<(&str, Vec<u8>)> = BINARIES.iter().map(|n| (*n, vec![1])).collect();
        let files = platform_files(windows, "0.6.0", b"MIT", &binaries);
        let names: Vec<_> = files
            .iter()
            .map(|(name, _, exec)| (name.as_str(), *exec))
            .collect();
        assert!(names.contains(&("bin/mcp-conformance.exe", true)));
        assert!(names.contains(&("package.json", false)));
    }

    #[test]
    fn each_bin_launcher_runs_its_own_binary() {
        let files = main_files("0.6.0", "readme", b"MIT");
        for name in BINARIES {
            let (_, script, executable) = files
                .iter()
                .find(|(path, ..)| *path == format!("bin/{name}.js"))
                .unwrap();
            let script = String::from_utf8(script.clone()).unwrap();
            assert!(script.starts_with("#!/usr/bin/env node\n") && *executable);
            assert!(script.contains(&format!(".run(\"{name}\")")));
        }
        assert!(
            LAUNCHER.contains("optionalDependencies"),
            "the launcher's platform list"
        );
    }
}
