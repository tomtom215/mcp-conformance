//! `cargo xtask sdk-matrix` — the cross-SDK matrix, as a projection of the
//! committed corpus.
//!
//! `interop/matrix.sh` records each official SDK's own conformance server,
//! driven by an official SDK client, through `mcp-trace-capture`; the traces
//! are committed under `corpus/captured/` (`2025-11-25`) and
//! `corpus/draft/captured/` (`2026-07-28`), named `sdk-<sdk>-<revision>.jsonl`,
//! and the golden suite pins their reports. This task turns those committed
//! golden reports into the book's matrix page, so the page is a projection of
//! the data (ADR-0001) rather than prose someone keeps:
//!
//! - **no flag** regenerates the block between the page's markers;
//! - **`--check`** (one of [`crate::GATES`]) fails when the block has drifted
//!   from the goldens, when a matrix trace has no golden, when the worked
//!   guide and the scheduled job stop sharing their commands (`guide`), or
//!   when a package manager's pin disagrees with the pins file (`pins`);
//! - **`--recaptured DIR`** compares a fresh `matrix.sh` run with the committed
//!   reports (`recapture`), which is what the scheduled job runs so the matrix
//!   stays true; with `BLESS=1` it copies the run's traces into the corpus.
//!
//! A cell with no committed capture is a server that does not serve that
//! revision — `matrix.sh` records the client's fallback and sets it aside —
//! and the page says so rather than leaving it blank.

// `unreachable_pub` (rustc) and `redundant_pub_crate` (clippy nursery) make
// opposite demands about items in a binary crate's private modules; this
// follows the rustc lint and quiets the clippy one, per its known-problems note.
#![allow(clippy::redundant_pub_crate)]

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use serde_json::Value;

mod guide;
mod pins;
mod recapture;
mod render;

/// The page the matrix is generated into.
const PAGE: &str = "book/src/sdk-matrix.md";

/// The pins file the versions are read from (`interop/sdk-pins.env`).
const PINS: &str = "interop/sdk-pins.env";

const BEGIN: &str =
    "<!-- sdk-matrix:begin (generated by `cargo xtask sdk-matrix`; do not edit by hand) -->";
const END: &str = "<!-- sdk-matrix:end -->";

/// One official SDK, as the matrix names it.
pub(crate) struct Sdk {
    /// The stem in trace names: `sdk-<key>-<revision>.jsonl`.
    key: &'static str,
    /// The display name.
    name: &'static str,
    /// The package the version pins.
    package: &'static str,
    /// The key in [`PINS`] holding the pinned version.
    pin: &'static str,
}

/// The Tier 1 SDKs the matrix covers, in the order the page lists them. The
/// TypeScript SDK has two lines, each a row: v1 (`@modelcontextprotocol/sdk`,
/// maintenance, `2025-11-25` at most) and v2 (`@modelcontextprotocol/server`
/// and its companions, which also serve `2026-07-28`).
pub(crate) const SDKS: [Sdk; 5] = [
    Sdk {
        key: "typescript",
        name: "TypeScript v1",
        package: "@modelcontextprotocol/sdk",
        pin: "TS_SDK_VERSION",
    },
    Sdk {
        key: "typescript-v2",
        name: "TypeScript v2",
        package: "@modelcontextprotocol/server",
        pin: "TS2_SDK_VERSION",
    },
    Sdk {
        key: "python",
        name: "Python",
        package: "mcp",
        pin: "PY_SDK_VERSION",
    },
    Sdk {
        key: "go",
        name: "Go",
        package: "go-sdk",
        pin: "GO_SDK_VERSION",
    },
    Sdk {
        key: "rust",
        name: "Rust",
        package: "rmcp",
        pin: "RUST_SDK_VERSION",
    },
];

/// A revision column: where its captures and their goldens live.
pub(crate) struct Revision {
    pub(crate) id: &'static str,
    pub(crate) traces: &'static str,
    pub(crate) goldens: &'static str,
    /// The client `matrix.sh` drives every server with at this revision.
    pub(crate) client: &'static str,
}

pub(crate) const REVISIONS: [Revision; 2] = [
    Revision {
        id: "2025-11-25",
        traces: "corpus/captured",
        goldens: "corpus/golden",
        client: "TypeScript SDK (v1) client (`ts-client.mjs`)",
    },
    Revision {
        id: "2026-07-28",
        traces: "corpus/draft/captured",
        goldens: "corpus/golden/draft",
        client: "Python SDK client (`py-client.py`)",
    },
];

/// The trace stem of one cell.
pub(crate) fn stem(sdk: &Sdk, revision: &Revision) -> String {
    format!("sdk-{}-{}", sdk.key, revision.id)
}

/// Generates (or, with `check`, verifies) the matrix page.
pub(crate) fn run(args: &[String], bless: bool) -> bool {
    let root = crate::workspace_root();
    match args.first().map(String::as_str) {
        None => generate(&root, false),
        Some("--check") => {
            // All three, so one red run names every disagreement.
            let page = generate(&root, true);
            let guide = guide::check(&root);
            let pins = load_pins(&root).is_ok_and(|pins| pins::check(&root, &pins));
            page && guide && pins
        }
        Some("--recaptured") => args.get(1).map_or_else(
            || {
                eprintln!("xtask: sdk-matrix — --recaptured needs the directory matrix.sh wrote");
                false
            },
            |dir| recapture::run(&root, Path::new(dir), bless),
        ),
        Some(other) => {
            eprintln!(
                "xtask: sdk-matrix — unknown argument {other:?}; expected --check or --recaptured DIR"
            );
            false
        }
    }
}

/// Renders the block from the committed goldens and splices it into the page.
fn generate(root: &Path, check: bool) -> bool {
    let rendered = match load_pins(root).and_then(|pins| {
        let cells = load_cells(root)?;
        Ok(render::block(&pins, &cells))
    }) {
        Ok(rendered) => rendered,
        Err(error) => {
            eprintln!("xtask: sdk-matrix — {error}");
            return false;
        }
    };
    let path = root.join(PAGE);
    let page = match fs::read_to_string(&path) {
        Ok(page) => page,
        Err(error) => {
            eprintln!("xtask: sdk-matrix — cannot read {PAGE}: {error}");
            return false;
        }
    };
    let Some(updated) = splice(&page, &rendered) else {
        eprintln!("xtask: sdk-matrix — {PAGE} lacks the `{BEGIN}` … `{END}` markers");
        return false;
    };
    if check {
        if updated == page {
            eprintln!("xtask: sdk-matrix — {PAGE} matches the committed reports");
            return true;
        }
        eprintln!(
            "xtask: sdk-matrix — {PAGE} has drifted from the committed golden reports; \
             run `cargo xtask sdk-matrix` and review the diff"
        );
        return false;
    }
    match fs::write(&path, updated) {
        Ok(()) => {
            eprintln!("xtask: sdk-matrix — {PAGE} regenerated");
            true
        }
        Err(error) => {
            eprintln!("xtask: sdk-matrix — cannot write {PAGE}: {error}");
            false
        }
    }
}

/// `KEY=value` lines of [`PINS`]; comments and blank lines skipped.
fn load_pins(root: &Path) -> Result<BTreeMap<String, String>, String> {
    let text = fs::read_to_string(root.join(PINS))
        .map_err(|error| format!("cannot read {PINS}: {error}"))?;
    let pins: BTreeMap<String, String> = text
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .filter_map(|line| line.split_once('='))
        .map(|(key, value)| (key.to_owned(), value.to_owned()))
        .collect();
    for sdk in &SDKS {
        if !pins.contains_key(sdk.pin) {
            return Err(format!("{PINS} does not pin {} ({})", sdk.name, sdk.pin));
        }
    }
    Ok(pins)
}

/// The committed golden of every cell, `None` where nothing was captured.
///
/// A trace without its golden is refused here rather than rendered as "not
/// served": the golden suite reports that mismatch too, but the page must not
/// be generated over it in the meantime.
pub(crate) fn load_cells(root: &Path) -> Result<Vec<Option<Value>>, String> {
    let mut cells = Vec::new();
    for sdk in &SDKS {
        for revision in &REVISIONS {
            let stem = stem(sdk, revision);
            let trace = root.join(revision.traces).join(format!("{stem}.jsonl"));
            let golden = root.join(revision.goldens).join(format!("{stem}.json"));
            if !golden.is_file() {
                if trace.is_file() {
                    return Err(format!(
                        "{} has no golden report; run `cargo xtask bless`",
                        trace.display()
                    ));
                }
                cells.push(None);
                continue;
            }
            let text = fs::read_to_string(&golden)
                .map_err(|error| format!("cannot read {}: {error}", golden.display()))?;
            let report: Value = serde_json::from_str(&text)
                .map_err(|error| format!("{} is not JSON: {error}", golden.display()))?;
            if report["revision"] != revision.id {
                return Err(format!(
                    "{} was judged at {}, not {}",
                    golden.display(),
                    report["revision"],
                    revision.id
                ));
            }
            cells.push(Some(report));
        }
    }
    Ok(cells)
}

/// `page` with the text between the markers replaced by `block`.
fn splice(page: &str, block: &str) -> Option<String> {
    let start = page.find(BEGIN)? + BEGIN.len();
    let end = start + page[start..].find(END)?;
    Some(format!("{}\n{block}{}", &page[..start], &page[end..]))
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn the_committed_page_is_in_sync() {
        assert!(generate(&crate::workspace_root(), true));
    }

    #[test]
    fn splice_replaces_only_the_block() {
        let page = format!("before\n{BEGIN}\nold\n{END}\nafter\n");
        let spliced = splice(&page, "new\n").unwrap();
        assert_eq!(spliced, format!("before\n{BEGIN}\nnew\n{END}\nafter\n"));
        assert!(splice("no markers", "x").is_none());
    }

    #[test]
    fn every_row_has_its_own_trace_stem() {
        let stems: std::collections::BTreeSet<_> = SDKS.iter().map(|sdk| sdk.key).collect();
        assert_eq!(stems.len(), SDKS.len(), "two SDKs share a trace stem");
    }

    #[test]
    fn every_sdk_is_pinned() {
        let pins = load_pins(&crate::workspace_root()).unwrap();
        for sdk in &SDKS {
            assert!(!pins[sdk.pin].is_empty(), "{} has an empty pin", sdk.name);
        }
    }
}
